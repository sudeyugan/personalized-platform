function cheekBraids(ctx: CanvasRenderingContext2D) {
  // Two narrow interwoven locks are one of the reference's signature details.
  for (const [startX, startY, slope] of [[98,109,1.25],[159,107,-0.9]]) {
    for (let link = 0; link < 8; link++) {
      const x = Math.round(startX + link * slope)
      const y = startY + link * 5
      polygon(ctx, p.hairShadow, [[x,y],[x+4,y+1],[x+6,y+4],[x+3,y+7],[x-1,y+4]])
      polygon(ctx, p.hairLight, [[x,y+1],[x+2,y+2],[x+3,y+4],[x+1,y+5],[x-1,y+3]])
      polygon(ctx, p.hair, [[x+3,y+2],[x+4,y+3],[x+4,y+5],[x+2,y+6],[x+1,y+5]])
      block(ctx, p.hairMid, x + 2, y + 3, 1, 1)
    }
    const x = Math.round(startX + 8 * slope)
    block(ctx, p.blueDeep, x, startY + 40, 5, 2)
    polygon(ctx, p.hair, [[x,startY+42],[x+4,startY+42],[x+4,startY+48],[x+2,startY+51],[x+1,startY+46]])
  }
}
